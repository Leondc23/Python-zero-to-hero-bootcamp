grades = [78, 52, 91, 62, 72]
print(min(grades)," is your lowest grade") # using the min() function to find the lowest number in the list
print(max(grades)," is your highest grade") #using the max() function to find the highest number in the list
print(sum(grades)/5, " is your overall average") #sum adds all the values in the list. they are divided by 5 as that is the total number of grades.